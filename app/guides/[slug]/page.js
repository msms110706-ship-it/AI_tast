export function generateStaticParams() {
  return Object.keys(guides).map((slug) => ({ slug }));
}

export function generateMetadata({ params }) {
  const guide = guides[params.slug];
  if (!guide) return {};
  return { title: guide.title, description: guide.intro, alternates: { canonical: `/guides/${params.slug}` } };
}

export default function GuidePage({ params }) {
  const guide = guides[params.slug];
  if (!guide) notFound();
  return <main className="info-page"><SiteHeader /><article className="info-main article-body">
    <p className="eyebrow">{guide.label}</p><h1>{guide.title}</h1><p className="article-lead">{guide.intro}</p>
    {guide.sections.map(([title, body]) => <section key={title}><h2>{title}</h2><p>{body}</p></section>)}
    <div className="article-note"><h2>바로 쓰는 체크리스트</h2><ul>{guide.checklist.map((item) => <li key={item}>{item}</li>)}</ul></div>
  </article><SiteFooter /></main>;
}
